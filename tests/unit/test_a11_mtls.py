@asynccontextmanager
async def owner_process(material, tmp_path):
    env = dict(os.environ)
    env["GITHUB_ACTIONS"] = "true"
    env["RUNNER_ENVIRONMENT"] = "github-hosted"
    env["PYTHONPATH"] = str(ROOT)
    server = await asyncio.create_subprocess_exec(
        sys.executable, str(ROOT / "tests/fixtures/a11_owner_process.py"),
        "--ca", str(material["ca"]),
        "--cert", str(material["server"]),
        "--key", str(material["server_key"]),
        "--client-hmac", str(material["client_hmac"]),
        "--owner-hmac", str(material["owner_hmac"]),
        "--replay-db", str(tmp_path / "owner-replay.db"),
        stdout=asyncio.subprocess.PIPE,
        stderr=asyncio.subprocess.DEVNULL,
        env=env, cwd=ROOT,
    )
    try:
        ready = await asyncio.wait_for(server.stdout.readline(), timeout=8)
        assert ready.startswith(b"A11_FIXTURE_READY:"), (
            "A11_OWNER_FIXTURE_DID_NOT_START"
        )
        port = int(ready.strip().split(b":")[-1])
        yield server, port
    finally:
        if server.returncode is None:
            server.terminate()
        try:
            await asyncio.wait_for(server.wait(), timeout=3)
        except asyncio.TimeoutError:
            server.kill()
            await server.wait()


def client_transport(material, port, *, ca=None, cert=None, key=None,
                     hostname=OWNER_DNS, timeout=2, failure_limit=2,
                     cooldown=0.15):
    context = make_client_context(
        ca=ca or material["ca"], cert=cert or material["client"],
        key=key or material["client_key"],
    )
    return LoopbackMtlsExchange(
        port=port, expected_owner_dns=hostname, context=context,
        timeout=timeout, failure_limit=failure_limit, cooldown=cooldown,
    )


def enabled_private(tmp_path):
    manager = PluginManager(tmp_path / "settings.db")
    raw = json.dumps({
        "schema_version": 1, "engine_id": "private_example",
        "engine_version": "1.0.0", "publisher": "fixture.owner",
        "visibility": "private", "adapter": "external_contract",
        "abi_version": 1, "markets": ["index"],
        "permissions": ["paper_analysis"],
    }, sort_keys=True).encode()
    digest = hashlib.sha256(raw).hexdigest()
    state = manager.register(raw, approved_sha256=digest)
    manager.set_enabled("private_example", enabled=True,
                        expected_revision=state.revision)
    return manager, digest


def setup_connector(material, tmp_path, exchange):
    manager, digest = enabled_private(tmp_path)
    fence = ReplayFence(tmp_path / "client-replay.db")
    keys = ConnectorKeys(
        "client_k1", material["client_hmac"].read_bytes(),
        "owner_k1", material["owner_hmac"].read_bytes(),
    )
    connector = PrivatePaperConnector(
        manager=manager, fence=fence, engine_id="private_example",
        engine_version="1.0.0", approved_digest=digest,
        keys=keys, exchange=exchange, timeout_seconds=3,
    )
    return manager, fence, connector


def sample_tick():
    return QuoteTick(
        INSTRUMENT, datetime.now(timezone.utc),
        Decimal("43000"), Decimal("43001"), QuoteOrigin.SYNTHETIC,
    )


def request_packet(material, *, nonce):
    now = int(time.time())
    t = sample_tick()
    body = {
        "version": 1, "key_id": "client_k1",
        "direction": "to_owner",
        "engine_id": "private_example", "engine_version": "1.0.0",
        "nonce": nonce, "request_nonce": "", "issued_at": now,
        "expires_at": now + 20,
        "payload": {
            "operation": "paper_analysis",
            "tick": {
                "market": "index", "provider": "fixture:quotes",
                "symbol": "US30", "timezone": "UTC", "quote_currency": "USD",
                "bid": "43000", "ask": "43001",
                "origin": "synthetic",
                "occurred_at": t.occurred_at.isoformat(),
            },
        },
    }
    return sign_packet(body, key=material["client_hmac"].read_bytes())


@pytest.mark.asyncio
async def test_separate_process_mtls_private_paper_e2e(tmp_path, material):
    async with owner_process(material, tmp_path) as (server, port):
        exchange = client_transport(material, port)
        manager, fence, connector = setup_connector(
            material, tmp_path, exchange,
        )
        registry = EngineRegistry()
        runner = MultiEngineRunner(registry, active=True)
        journal = PaperJournal(tmp_path / "paper.db")
        platform = ManagedPaperPlatform(
            manager, registry, runner, journal, enabled=True,
        )
        plugin = ExternalPaperEngine("private_example", "1.0.0", connector)
        tick = sample_tick()
        policy = SessionPolicy(
            "UTC", (
                TradingWindow(
                    tick.occurred_at.weekday(),
                    __import__("datetime").time(0, 0),
                    __import__("datetime").time(23, 59),
                ),
            ), verified=True,
        )
        binding = EngineBinding(
            EngineDescriptor("private_example", "1.0.0",
                             frozenset({Market.INDEX})),
            frozenset({INSTRUMENT}), policy, enabled=True,
        )
        platform.attach(binding, plugin)
        result = await platform.process(tick, now=tick.occurred_at)
        assert result.stored == 1 and result.status == "RECORDED"
        assert journal.count() == 1
        assert exchange.health.state == "READY_FOR_OFFLINE_TEST"
        assert not exchange.health.live_engine_authorized
        assert not connector.status.real_owner_authenticated
        assert not connector.status.license_authority_verified
        assert server.returncode is None
        journal.close()
        fence.close()
        manager.close()


