@pytest.mark.asyncio
async def test_server_shutdown_triggers_circuit_without_retry(tmp_path, material):
    async with owner_process(material, tmp_path) as (server, port):
        transport = client_transport(
            material, port, failure_limit=2, cooldown=0.15,
            timeout=0.5,
        )
        packet = request_packet(material, nonce="f" * 32)
        assert await transport(packet)
        server.terminate()
        await asyncio.wait_for(server.wait(), timeout=3)
        for _ in range(2):
            with pytest.raises(TransportRefused, match="EXCHANGE_UNAVAILABLE"):
                await transport(packet)
        assert transport.health.state == "OPEN"
        with pytest.raises(TransportRefused, match="CIRCUIT_OPEN"):
            await transport(packet)
        await asyncio.sleep(0.18)
        assert transport.health.state == "DEGRADED"


