def _openssl(*args):
    result = subprocess.run(
        ["openssl", *map(str, args)],
        check=False, capture_output=True, text=True, timeout=20,
    )
    if result.returncode:
        raise AssertionError("A11_EPHEMERAL_CERT_GENERATION_FAILED")


def _ca(directory, name):
    key, cert = directory / f"{name}.key", directory / f"{name}.crt"
    _openssl(
        "req", "-x509", "-newkey", "rsa:2048", "-nodes",
        "-days", "2", "-keyout", key, "-out", cert,
        "-subj", f"/CN={name}.fixture-ca",
        "-addext", "basicConstraints=critical,CA:TRUE",
        "-addext", "keyUsage=critical,keyCertSign,cRLSign",
    )
    return cert, key


def _identity(directory, name, dns, ca, ca_key, *, role):
    key, csr, cert = (
        directory / f"{name}.key", directory / f"{name}.csr",
        directory / f"{name}.crt",
    )
    _openssl(
        "req", "-newkey", "rsa:2048", "-nodes", "-keyout", key,
        "-out", csr, "-subj", f"/CN={dns}",
    )
    extensions = directory / f"{name}.ext"
    extensions.write_text(
        f"subjectAltName=DNS:{dns}\nextendedKeyUsage={role}\n"
        "keyUsage=digitalSignature,keyEncipherment\n",
    )
    _openssl(
        "x509", "-req", "-in", csr, "-CA", ca, "-CAkey", ca_key,
        "-CAcreateserial", "-out", cert, "-days", "2",
        "-extfile", extensions,
    )
    return cert, key


