def test_insecure_transport_context_and_remote_host_disallowed(material):
    import ssl
    bare = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
    bare.check_hostname = False
    bare.verify_mode = ssl.CERT_NONE
    with pytest.raises(TransportRefused):
        LoopbackMtlsExchange(
            port=1234, expected_owner_dns=OWNER_DNS, context=bare,
        )
    secure = make_client_context(
        ca=material["ca"], cert=material["client"],
        key=material["client_key"],
    )
    with pytest.raises(TransportRefused):
        LoopbackMtlsExchange(
            port=1234, expected_owner_dns="example.com", context=secure,
        )
